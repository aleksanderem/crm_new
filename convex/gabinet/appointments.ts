/**
 * Internal mutation that handles post-write side effects after the
 * appointment has been written to Supabase by the create action.
 */
export const _createSideEffects = internalMutation({
  args: {
    // Appointment data (already written to Supabase)
    appointmentId: v.string(),
    organizationId: v.id("organizations"),
    patientId: v.string(),
    treatmentId: v.string(),
    employeeId: v.string(),
    date: v.string(),
    startTime: v.string(),
    endTime: v.string(),
    notes: v.optional(v.string()),
    status: v.string(),
    isRecurring: v.boolean(),
    recurringGroupId: v.optional(v.string()),
    sendReminder: v.boolean(),
    reminderOverrides: v.optional(v.string()), // JSON: per-appointment channel overrides
    createdBy: v.string(),
    createdAt: v.number(),
    // Resolved names for calendar title
    patientName: v.string(),
    treatmentName: v.string(),
    // Patient contact info for automation event
    patientEmail: v.optional(v.string()),
    patientPhone: v.optional(v.string()),
    // Recurring series: per-occurrence appointment ID, date, index and times
    // (times may differ from the base when the user customizes them — #665).
    recurringAppointments: v.optional(v.array(v.object({
      appointmentId: v.string(),
      date: v.string(),
      recurringIndex: v.number(),
      startTime: v.optional(v.string()),
      endTime: v.optional(v.string()),
    }))),
    // Package usage (already resolved by action)
    packageUsageId: v.optional(v.string()),
    // Pre-resolved Supabase UUIDs from the parent action (scheduledActivities
    // are now written by the action, not here).
    scheduledActivityId: v.string(),
    recurActivityIds: v.array(v.object({
      appointmentId: v.string(),
      activityId: v.string(),
    })),
  },
  handler: async (ctx, args) => {
    const now = args.createdAt;
    const createdByUserId = args.createdBy as Id<"users">;

    const scheduledActivityId = args.scheduledActivityId;

    // --- 2. Emit automation event ---
    await emitAutomationEvent(ctx, {
      organizationId: args.organizationId,
      module: "gabinet",
      eventType: "gabinet.appointment.created",
      entityType: "gabinetAppointment",
      entityId: args.appointmentId,
      actorUserId: createdByUserId,
      correlationKey: `appointment:${args.appointmentId}`,
      eventIdempotencyKey: `automation-event:${args.organizationId}:${args.appointmentId}:created`,
      payload: {
        organizationId: String(args.organizationId),
        appointmentId: args.appointmentId,
        patientId: args.patientId,
        treatmentId: args.treatmentId,
        employeeId: args.employeeId,
        date: args.date,
        startTime: args.startTime,
        endTime: args.endTime,
        status: "scheduled",
        patientEmail: args.patientEmail,
        patientPhone: args.patientPhone,
        patientName: args.patientName,
        treatmentName: args.treatmentName,
        employeeName: args.employeeId,
        createdBy: args.createdBy,
      },
    });

    // --- 3. Auto-generate appointment documents ---
    // "before_start" docs go straight to the patient for signing before the
    // visit. "during_visit" docs are generated upfront so they appear in the
    // checklist immediately, but emails are deferred — the employee fills /
    // sends them during the visit itself.
    await autoGenerateAppointmentDocuments(ctx, {
      organizationId: args.organizationId,
      appointmentId: args.appointmentId as Id<"gabinetAppointments">,
      treatmentId: args.treatmentId as Id<"gabinetTreatments">,
      patientId: args.patientId as Id<"gabinetPatients">,
      createdBy: createdByUserId,
      timing: "before_start",
    });
    await autoGenerateAppointmentDocuments(ctx, {
      organizationId: args.organizationId,
      appointmentId: args.appointmentId as Id<"gabinetAppointments">,
      treatmentId: args.treatmentId as Id<"gabinetTreatments">,
      patientId: args.patientId as Id<"gabinetPatients">,
      createdBy: createdByUserId,
      timing: "during_visit",
      deferEmails: true,
    });

    // --- 4. Calendar events for recurring appointments already written to Supabase by the action ---
    const recurringAppointments = args.recurringAppointments ?? [];
    const recurActivityIds = args.recurActivityIds;

    // --- 5. Log activity ---
    await logActivity(ctx, {
      organizationId: args.organizationId,
      entityType: "gabinetAppointment",
      entityId: args.appointmentId,
      action: "created",
      description: `Created appointment for ${args.date} at ${args.startTime}`,
      performedBy: createdByUserId,
    });

    // --- 6. Schedule reminders (inline — avoid DB read since appointment is in Supabase) ---
    if (args.sendReminder) {
      try {
        // Read org settings from Supabase (primary store) to get 4-toggle channel config.
        const remDb = createSupabaseDb();
        const supaOrgSettings = await remDb.query("orgSettings")
          .eq("organizationId", String(args.organizationId))
          .first() as Record<string, unknown> | null;

        // Parse per-appointment overrides from dialog.
        let apptOverrides: Record<string, boolean> = {};
        if (args.reminderOverrides) {
          try { apptOverrides = JSON.parse(args.reminderOverrides); } catch {}
        }

        // Determine which timings to schedule based on merged settings.
        // If no 4-toggle settings exist (legacy orgs), fall back to single 24h reminder.
        const has4ToggleConfig =
          supaOrgSettings?.reminderSms48h !== null && supaOrgSettings?.reminderSms48h !== undefined ||
          supaOrgSettings?.reminderSms24h !== null && supaOrgSettings?.reminderSms24h !== undefined ||
          supaOrgSettings?.reminderEmail48h !== null && supaOrgSettings?.reminderEmail48h !== undefined ||
          supaOrgSettings?.reminderEmail24h !== null && supaOrgSettings?.reminderEmail24h !== undefined ||
          Object.keys(apptOverrides).length > 0;

        let timingsHours: number[];
        if (has4ToggleConfig) {
          timingsHours = [];
          const need48h =
            (apptOverrides.sms48h !== undefined ? apptOverrides.sms48h : Boolean(supaOrgSettings?.reminderSms48h)) ||
            (apptOverrides.email48h !== undefined ? apptOverrides.email48h : Boolean(supaOrgSettings?.reminderEmail48h));
          const need24h =
            (apptOverrides.sms24h !== undefined ? apptOverrides.sms24h : Boolean(supaOrgSettings?.reminderSms24h)) ||
            (apptOverrides.email24h !== undefined ? apptOverrides.email24h : Boolean(supaOrgSettings?.reminderEmail24h));
          if (need48h) timingsHours.push(48);
          if (need24h) timingsHours.push(24);
        } else {
          // Legacy: single reminder at configured hours (default 24)
          const orgSettings = await ctx.db
            .query("orgSettings")
            .withIndex("by_org", (q) => q.eq("organizationId", args.organizationId))
            .unique();
          const reminderHours = (orgSettings as any)?.reminderHoursBefore ?? 24;
          timingsHours = [reminderHours];
        }

        const scheduleReminderFor = async (
          apptId: string,
          apptDate: string,
          apptStartTime: string,
          hoursAhead: number,
        ): Promise<boolean> => {
          const appointmentMs = new Date(`${apptDate}T${apptStartTime}:00`).getTime();
          const reminderMs = appointmentMs - hoursAhead * 60 * 60 * 1000;
          if (reminderMs <= Date.now()) return false;
          const reminderId = await ctx.db.insert("appointmentReminders", {
            organizationId: args.organizationId,
            appointmentId: apptId as any,
            type: "notification",
            scheduledFor: reminderMs,
            status: "pending",
            createdAt: now,
          });
          await ctx.scheduler.runAfter(
            reminderMs - Date.now(),
            internal.gabinet.appointmentReminders.sendReminder,
            { reminderId },
          );
          return true;
        };

        let baseApptScheduled = 0;
        for (const hours of timingsHours) {
          if (await scheduleReminderFor(args.appointmentId, args.date, args.startTime, hours)) {
            baseApptScheduled++;
          }
          for (const recur of recurringAppointments) {
            await scheduleReminderFor(
              recur.appointmentId,
              recur.date,
              recur.startTime ?? args.startTime,
              hours,
            );
          }
        }

        // Short-notice appointment: all configured reminder slots are in the past.
        // Send an immediate booking confirmation SMS so the patient still gets notified.
        if (timingsHours.length > 0 && baseApptScheduled === 0 && args.patientPhone) {
          const needSms = has4ToggleConfig
            ? Boolean(
                (apptOverrides.sms48h !== undefined ? apptOverrides.sms48h : supaOrgSettings?.reminderSms48h) ||
                (apptOverrides.sms24h !== undefined ? apptOverrides.sms24h : supaOrgSettings?.reminderSms24h)
              )
            : true;
          if (needSms) {
            await ctx.runMutation(internal.gabinet.appointmentSms.queueConfirmationRequest, {
              organizationId: args.organizationId,
              appointmentId: args.appointmentId,
              trigger: "booking",
            });
          }
        }
      } catch (e) {
        console.warn("Reminder scheduling failed (non-fatal):", e);
      }
    }

    return { scheduledActivityId, recurActivityIds };
  },
});

