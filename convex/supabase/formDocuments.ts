/**
 * Convex → Supabase Form Document Write Actions
 *
 * Internal actions that persist form document data to PostgreSQL via Supabase
 * service-role client (bypasses RLS). Dual-write pattern: Convex mutations
 * write to Convex first, then schedule these actions to replicate to Supabase.
 */

import { v } from "convex/values";
import { internalAction } from "@cvx/_generated/server";
import { createServiceRoleClient } from "./client";

export const writeFormDocumentToSupabase = internalAction({
  args: {
    documentId: v.string(),
    organizationId: v.string(),
    templateId: v.string(),
    title: v.string(),
    responseData: v.string(),
    entityType: v.string(),
    entityId: v.string(),
    scopeEntities: v.optional(v.string()),
    status: v.string(),
    signatureData: v.optional(v.string()),
    signedAt: v.optional(v.number()),
    signedByName: v.optional(v.string()),
    signedByEmail: v.optional(v.string()),
    signedByIp: v.optional(v.string()),
    signatureVerificationMethod: v.optional(v.string()),
    signingToken: v.optional(v.string()),
    signingTokenExpiresAt: v.optional(v.number()),
    signingEmailSentAt: v.optional(v.number()),
    signingReminderCount: v.optional(v.number()),
    timing: v.optional(v.string()),
    autoGenerated: v.optional(v.boolean()),
    pdfStorageId: v.optional(v.string()),
    pdfGeneratedAt: v.optional(v.number()),
    createdBy: v.string(),
    createdAt: v.number(),
    updatedAt: v.number(),
  },
  returns: v.object({ success: v.boolean(), id: v.string() }),
  handler: async (_ctx, args): Promise<{ success: boolean; id: string }> => {
    const client = createServiceRoleClient();

    const row = {
      id: args.documentId,
      organization_id: args.organizationId,
      template_id: args.templateId,
      title: args.title,
      response_data: args.responseData,
      entity_type: args.entityType,
      entity_id: args.entityId,
      scope_entities: args.scopeEntities ?? null,
      status: args.status,
      signature_data: args.signatureData ?? null,
      signed_at: args.signedAt ?? null,
      signed_by_name: args.signedByName ?? null,
      signed_by_email: args.signedByEmail ?? null,
      signed_by_ip: args.signedByIp ?? null,
      signature_verification_method: args.signatureVerificationMethod ?? null,
      signing_token: args.signingToken ?? null,
      signing_token_expires_at: args.signingTokenExpiresAt ?? null,
      signing_email_sent_at: args.signingEmailSentAt ?? null,
      signing_reminder_count: args.signingReminderCount ?? null,
      timing: args.timing ?? null,
      auto_generated: args.autoGenerated ?? null,
      pdf_storage_id: args.pdfStorageId ?? null,
      pdf_generated_at: args.pdfGeneratedAt ?? null,
      created_by: args.createdBy,
      created_at: args.createdAt,
      updated_at: args.updatedAt,
    };

    const { data, error } = await client
      .from("form_documents")
      .upsert(row, { onConflict: "id" })
      .select("id")
      .single();

    if (error) {
      const msg = `Supabase write failed for form_document: ${error.message} (code=${error.code})`;
      console.error(msg);
      throw new Error(msg);
    }

    if (!data || typeof data.id !== "string") {
      throw new Error("Supabase write returned malformed response: missing id");
    }

    console.info(`Form document written to Supabase id=${data.id} org=${args.organizationId}`);
    return { success: true, id: data.id };
  },
});
